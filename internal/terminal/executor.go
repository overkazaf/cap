package terminal

import (
	"context"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"fmt"
	"os/exec"
	"strings"
	"sync"
	"time"
)

const confirmationTTL = 5 * time.Minute

// ErrConfirmationRequired reports that command is not allowlisted. The caller
// should display it to a human and retry with Confirm and the returned token.
var ErrConfirmationRequired = errors.New("terminal: confirmation required")

var (
	ErrEmptyCommand = errors.New("terminal: command is required")
	ErrInvalidEntry = errors.New("terminal: allowlist entry must name an executable and contain no shell metacharacters")
)

type Request struct {
	Command string
	// Confirm explicitly authorizes the exact command named by
	// ConfirmationToken. It must be false for the initial safety check.
	Confirm bool
	// ConfirmationToken is generated by the ConfirmationRequired response.
	ConfirmationToken string
	// Allowlist hashes pre-approved exact commands. The caller may load it
	// from persistent settings; changes take effect on the next request.
	Allowlist map[string]string
	// Timeout bounds execution. Zero selects two minutes.
	Timeout time.Duration
	// Env is passed through unchanged; nil inherits the parent environment.
	Env []string
}

type Result struct {
	Executed bool
	Output   string
	Err      error
	// ConfirmationToken is set whenever Err matches ErrConfirmationRequired.
	// It expires after confirmationTTL and authorizes only Command.
	ConfirmationToken string
}

type Executor struct {
	shell   string
	mu      sync.Mutex
	pending map[string]pendingConfirmation
}

type pendingConfirmation struct {
	command   string
	expiresAt time.Time
}

func New(shell string) *Executor {
	if strings.TrimSpace(shell) == "" {
		shell = "/bin/sh"
	}
	return &Executor{shell: shell, pending: make(map[string]pendingConfirmation)}
}

func (e *Executor) Execute(ctx context.Context, request Request) Result {
	command := strings.TrimSpace(request.Command)
	if command == "" {
		return Result{Err: ErrEmptyCommand}
	}
	if isAllowlisted(command, commandToken(command), request.Allowlist) {
		return e.execute(ctx, command, request)
	}

	token := commandToken(command)
	e.mu.Lock()
	pending, exists := e.pending[token]
	now := time.Now()
	valid := exists && now.Before(pending.expiresAt) && pending.command == command
	if !valid {
		e.deleteExpiredLocked(now)
		e.pending[token] = pendingConfirmation{command: command, expiresAt: now.Add(confirmationTTL)}
	}
	e.mu.Unlock()

	if request.Confirm && valid && request.ConfirmationToken == token {
		return e.execute(ctx, command, request)
	}
	return Result{
		Err:               fmt.Errorf("%w: %s", ErrConfirmationRequired, command),
		ConfirmationToken: token,
	}
}

func (e *Executor) execute(ctx context.Context, command string, request Request) Result {
	timeout := request.Timeout
	if timeout <= 0 {
		timeout = 2 * time.Minute
	}
	execCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()

	cmd := exec.CommandContext(execCtx, e.shell, "-c", command)
	cmd.Env = request.Env
	output, err := cmd.CombinedOutput()
	result := Result{Executed: err == nil, Output: string(output), Err: err}
	if execCtx.Err() != nil {
		result.Err = fmt.Errorf("terminal: command timed out after %s: %w", timeout, execCtx.Err())
	}
	return result
}

func (e *Executor) deleteExpiredLocked(now time.Time) {
	for token, pending := range e.pending {
		if !now.Before(pending.expiresAt) {
			delete(e.pending, token)
		}
	}
}

func isAllowlisted(command, token string, approved map[string]string) bool {
	if token == "" {
		return false
	}
	if expected, key := approved[canonicalCommand(command)]; key && constantTimeEquals(token, expected) {
		return true
	}
	return false
}

func commandToken(command string) string {
	digest := sha256.Sum256([]byte(canonicalCommand(command)))
	return base64.RawURLEncoding.EncodeToString(digest[:])
}

func canonicalCommand(command string) string {
	return strings.Join(strings.Fields(command), " ")
}

func constantTimeEquals(a, b string) bool {
	return subtle.ConstantTimeCompare([]byte(a), []byte(b)) == 1
}
